#!/usr/bin/env python3
"""Split the frozen manifest into stratified batch files for run_batch.ps1.

A 250-case campaign is run in sittings, and a sitting can end early: quota runs
out, the VPN drops, the machine reboots. If batches were alphabetical, stopping
after batch 2 would leave a sample skewed toward whatever categories sort first,
and the partial pass rate would not mean anything.

So deal instead of chunk. Cases are sorted by (category, difficulty, case_id)
and dealt round-robin into N batches, which puts nearly equal shares of every
stratum in each batch. Any prefix of the batches is then a fair sample of the
whole dataset, and a campaign stopped halfway still reports a usable number.

Dealing from a sorted list is deterministic, so this needs no random seed and
regenerating the files always reproduces them exactly.

    python tools/stage2/make_batches.py --experiment <config.json> --batches 5

Batches do not change what an experiment may run; case_ids in the config still
governs that. They only decide the order cases are attempted in.
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--experiment", required=True)
    parser.add_argument("--batches", type=int, default=5)
    parser.add_argument("--out-dir", default=str(REPO_ROOT / "benchmark" / "stage2" / "batches"))
    parser.add_argument("--prefix", default="batch")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if args.batches < 1:
        print("--batches must be at least 1", file=sys.stderr)
        return 2

    config = json.loads(Path(args.experiment).read_text(encoding="utf-8"))
    manifest = json.loads((REPO_ROOT / config["dataset_manifest"]).read_text(encoding="utf-8"))
    cases = manifest["cases"]

    # Restrict to what this experiment is actually configured to run, so the
    # batches never name a case the runner would refuse.
    configured = set(str(item) for item in (config.get("case_ids") or []))
    if configured:
        cases = [c for c in cases if c["case_id"] in configured]

    ordered = sorted(
        cases,
        key=lambda c: (str(c.get("category")), str(c.get("difficulty")), c["case_id"]),
    )
    batches: list[list[dict]] = [[] for _ in range(args.batches)]
    for index, case in enumerate(ordered):
        batches[index % args.batches].append(case)

    out_dir = Path(args.out_dir)
    width = len(str(args.batches))
    print(f"{len(ordered)} cases -> {args.batches} batches")
    for number, batch in enumerate(batches, 1):
        name = f"{args.prefix}{number:0{width}d}.txt"
        counts = collections.Counter(str(c.get("difficulty")) for c in batch)
        summary = " ".join(f"{k}={counts[k]}" for k in sorted(counts))
        print(f"  {name}: {len(batch):3} cases  {summary}")
        if args.dry_run:
            continue
        lines = [
            f"# {name} - batch {number} of {args.batches}, {len(batch)} cases",
            "# Generated by tools/stage2/make_batches.py; do not hand-edit.",
            "# Cases are dealt round-robin from a (category, difficulty, case_id)",
            "# sort, so each batch mirrors the full dataset and any prefix of the",
            "# batches is a fair sample. Regenerating reproduces this exactly.",
            "#",
            "#   .\\tools\\stage2\\run_batch.ps1 -Experiment <config.json> -CaseFile "
            f"benchmark\\stage2\\batches\\{name}",
            "",
        ]
        lines.extend(c["case_id"] for c in batch)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / name).write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(len(b) for b in batches)
    if total != len(ordered):
        print(f"internal error: dealt {total} of {len(ordered)}", file=sys.stderr)
        return 2
    if not args.dry_run:
        print(f"\nwrote {args.batches} files to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
